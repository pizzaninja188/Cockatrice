#[derive(Debug, Deserialize)]
pub struct BulkMetadata {
    #[serde(rename = "type")]
    pub kind: String,
    pub id: String,
    pub updated_at: String,
    pub jsonl_download_uri: String,
    pub sha256: String,
}

pub fn hash_file(path: &Path) -> Result<String, String> {
    let mut file = fs::File::open(path)
        .map_err(|error| format!("cannot open {} for hashing: {error}", path.display()))?;
    let mut hasher = Sha256::new();
    let mut buffer = [0u8; 64 * 1024];
    loop {
        let read = file
            .read(&mut buffer)
            .map_err(|error| format!("cannot hash {}: {error}", path.display()))?;
        if read == 0 {
            break;
        }
        hasher.update(&buffer[..read]);
    }
    Ok(format!("{:x}", hasher.finalize()))
}

pub fn provenance_from_metadata(
    metadata: &BulkMetadata,
    actual_sha256: &str,
) -> Result<String, String> {
    if metadata.kind != "oracle_cards" {
        return Err(format!(
            "metadata describes {:?}, expected oracle_cards",
            metadata.kind
        ));
    }
    if !metadata.sha256.eq_ignore_ascii_case(actual_sha256) {
        return Err(format!(
            "bulk SHA-256 mismatch: metadata has {}, input is {actual_sha256}",
            metadata.sha256
        ));
    }
    if metadata.id.trim().is_empty()
        || metadata.updated_at.trim().is_empty()
        || metadata.jsonl_download_uri.trim().is_empty()
    {
        return Err("bulk metadata is missing id, updated_at, or jsonl_download_uri".into());
    }
    Ok(format!(
        "generated by gen-cards from Scryfall {} {} updated {} sha256:{}",
        metadata.kind, metadata.id, metadata.updated_at, actual_sha256
    ))
}

pub fn load_provenance(input: &Path, metadata_path: &Path) -> Result<String, String> {
    let actual_sha256 = hash_file(input)?;
    let metadata_file = fs::File::open(metadata_path).map_err(|error| {
        format!(
            "cannot open bulk metadata {}: {error}; fetch the input with fetch-scryfall-bulk",
            metadata_path.display()
        )
    })?;
    let metadata: BulkMetadata = serde_json::from_reader(BufReader::new(metadata_file))
        .map_err(|error| format!("cannot parse {}: {error}", metadata_path.display()))?;
    provenance_from_metadata(&metadata, &actual_sha256)
}

pub fn default_metadata_path(input: &Path) -> PathBuf {
    PathBuf::from(format!("{}.meta.json", input.display()))
}

pub fn for_each_jsonl<R: BufRead>(
    mut reader: R,
    mut visit: impl FnMut(Value) -> bool,
) -> Result<usize, String> {
    let mut line = String::new();
    let mut line_number = 0usize;
    loop {
        line.clear();
        let bytes = reader
            .read_line(&mut line)
            .map_err(|error| format!("failed to read JSONL line {}: {error}", line_number + 1))?;
        if bytes == 0 {
            break;
        }
        line_number += 1;
        if line.trim().is_empty() {
            continue;
        }
        let value = serde_json::from_str(&line)
            .map_err(|error| format!("invalid JSONL record on line {line_number}: {error}"))?;
        if !visit(value) {
            break;
        }
    }
    Ok(line_number)
}

pub fn for_each_gzipped_jsonl(
    path: &Path,
    visit: impl FnMut(Value) -> bool,
) -> Result<usize, String> {
    let file =
        fs::File::open(path).map_err(|error| format!("cannot open {}: {error}", path.display()))?;
    let decoder = GzDecoder::new(file);
    for_each_jsonl(BufReader::new(decoder), visit)
}

pub fn read_gzipped_jsonl(reader: impl Read) -> Result<Vec<Value>, String> {
    let decoder = GzDecoder::new(reader);
    let mut values = Vec::new();
    for_each_jsonl(BufReader::new(decoder), |value| {
        values.push(value);
        true
    })?;
    Ok(values)
}

/// Bucket directory for a card id: its first ASCII letter, else `_`.
pub fn bucket(id: &str) -> char {
    id.chars()
        .find(|c| c.is_ascii_alphabetic())
        .map(|c| c.to_ascii_lowercase())
        .unwrap_or('_')
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourcePresentationFace {
    pub name: String,
    pub oracle_text_sha256: String,
    pub lines: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourcePresentationCard {
    pub name: String,
    pub faces: Vec<SourcePresentationFace>,
}

pub fn normalized_oracle_text_sha256(text: &str) -> String {
    let normalized = crate::external_oracle_lines(text).join("\n");
    format!("{:x}", Sha256::digest(normalized.as_bytes()))
}

pub fn source_presentation_card(card: &Value) -> Option<SourcePresentationCard> {
    // Token variants have their own display identity. A same-name token must not make a
    // normal card's fingerprint ambiguous (Ajani's Pridemate and Spellgorger Weird).
    if matches!(
        str_field(card, "layout"),
        "token" | "double_faced_token" | "emblem"
    ) {
        return None;
    }
    let name = str_field(card, "name").trim();
    if name.is_empty() {
        return None;
    }
    let faces = card
        .get("card_faces")
        .and_then(Value::as_array)
        .filter(|faces| !faces.is_empty())
        .and_then(|faces| {
            faces
                .iter()
                .map(|face| {
                    let face_name = str_field(face, "name").trim();
                    let oracle_text = str_field(face, "oracle_text");
                    (!face_name.is_empty() && !oracle_text.is_empty()).then(|| {
                        SourcePresentationFace {
                            name: face_name.to_string(),
                            oracle_text_sha256: normalized_oracle_text_sha256(oracle_text),
                            lines: crate::external_oracle_lines(oracle_text),
                        }
                    })
                })
                .collect::<Option<Vec<_>>>()
        })
        .or_else(|| {
            let oracle_text = str_field(card, "oracle_text");
            (!oracle_text.is_empty()).then(|| {
                vec![SourcePresentationFace {
                    name: name.to_string(),
                    oracle_text_sha256: normalized_oracle_text_sha256(oracle_text),
                    lines: crate::external_oracle_lines(oracle_text),
                }]
            })
        })?;
    Some(SourcePresentationCard {
        name: name.to_string(),
        faces,
    })
}

pub fn add_presentation_source(
    sources: &mut HashMap<String, SourcePresentationCard>,
    ambiguous: &mut HashSet<String>,
    card_id: &str,
    card: &Value,
) {
    if ambiguous.contains(card_id) {
        return;
    }
    if let Some(source) = source_presentation_card(card) {
        match sources.get(card_id) {
            Some(existing) if existing != &source => {
                sources.remove(card_id);
                ambiguous.insert(card_id.to_string());
            }
            None => {
                sources.insert(card_id.to_string(), source);
            }
            _ => {}
        }
    }
}

pub fn collect_presentation_sources(
    input: &Path,
    registry: &CardRegistry,
) -> Result<HashMap<String, SourcePresentationCard>, String> {
    let mut sources = HashMap::new();
    let mut ambiguous = HashSet::new();
    for_each_gzipped_jsonl(input, |card| {
        if let Some(card_id) = registry.id_for_name(str_field(&card, "name")) {
            add_presentation_source(&mut sources, &mut ambiguous, card_id, &card);
        }
        true
    })?;
    Ok(sources)
}

pub fn render_presentation_registry(
    provenance: &str,
    registry: &CardRegistry,
    source_cards: &HashMap<String, SourcePresentationCard>,
) -> String {
    let mut definitions = registry.definitions().collect::<Vec<_>>();
    definitions.sort_by(|left, right| left.id.cmp(&right.id));
    let mut output = format!(
        "# {provenance}\n# card_id\tcard_name\tface_id\tface_name\tnormalized_oracle_text_sha256\n"
    );
    for definition in definitions {
        let Some(source) = source_cards.get(&definition.id) else {
            continue;
        };
        for face in &definition.faces {
            let matching = if definition.faces.len() == 1 && source.faces.len() == 1 {
                source.faces.first()
            } else {
                source
                    .faces
                    .iter()
                    .find(|candidate| normalize_name(&candidate.name) == normalize_name(&face.name))
            };
            let Some(source_face) = matching else {
                continue;
            };
            output.push_str(&format!(
                "{}\t{}\t{}\t{}\t{}\n",
                definition.id,
                source.name.replace(['\t', '\n', '\r'], " "),
                face.face_id,
                source_face.name.replace(['\t', '\n', '\r'], " "),
                source_face.oracle_text_sha256,
            ));
        }
    }
    output
}

pub const GENERATED_PROVENANCE_PREFIX: &str = "// generated by gen-cards from Scryfall ";

pub fn collect_ron_files(root: &Path, files: &mut Vec<PathBuf>) -> Result<(), String> {
    if !root.exists() {
        return Ok(());
    }
    for entry in
        fs::read_dir(root).map_err(|error| format!("cannot read {}: {error}", root.display()))?
    {
        let path = entry
            .map_err(|error| format!("cannot read {} entry: {error}", root.display()))?
            .path();
        if path.is_dir() {
            collect_ron_files(&path, files)?;
        } else if path.extension().and_then(|value| value.to_str()) == Some("ron") {
            files.push(path);
        }
    }
    Ok(())
}

pub fn check_presentation_registry(path: &Path, expected: &str) -> Result<(), String> {
    match fs::read_to_string(path) {
        Ok(actual) if actual == expected => Ok(()),
        Ok(_) => Err(format!("content drift: {}", path.display())),
        Err(error) => Err(format!("missing {}: {error}", path.display())),
    }
}

pub fn write_if_changed(path: &Path, contents: &str) -> io::Result<bool> {
    match fs::read(path) {
        Ok(existing) if existing == contents.as_bytes() => Ok(false),
        Ok(_) => {
            fs::write(path, contents)?;
            Ok(true)
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            fs::write(path, contents)?;
            Ok(true)
        }
        Err(error) => Err(error),
    }
}

pub fn refresh_presentation_registry(path: &Path, expected: &str) -> Result<bool, String> {
    write_if_changed(path, expected).map_err(|error| error.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    use flate2::write::GzEncoder;
    use flate2::Compression;
    use serde_json::json;
    use std::io::Write;

    #[test]
    fn provenance_uses_verified_bulk_metadata_instead_of_wall_clock() {
        let metadata = BulkMetadata {
            kind: "oracle_cards".into(),
            id: "bulk-id".into(),
            updated_at: "2026-08-25T16:01:52.435-05:00".into(),
            jsonl_download_uri: "https://data.scryfall.io/oracle-cards/example.jsonl.gz".into(),
            sha256: "abc123".into(),
        };
        assert_eq!(
            provenance_from_metadata(&metadata, "abc123").unwrap(),
            "generated by gen-cards from Scryfall oracle_cards bulk-id updated 2026-08-25T16:01:52.435-05:00 sha256:abc123"
        );
        assert!(provenance_from_metadata(&metadata, "different").is_err());
    }

    #[test]
    fn provenance_rejects_invalid_type_and_missing_or_blank_sidecar_fields() {
        let base = json!({
            "type":"oracle_cards", "id":"bulk-id", "updated_at":"date",
            "jsonl_download_uri":"https://example.invalid/bulk.gz", "sha256":"abc123"
        });
        let valid: BulkMetadata = serde_json::from_value(base.clone()).unwrap();
        assert!(provenance_from_metadata(&valid, "abc123").is_ok());
        for field in ["type", "id", "updated_at", "jsonl_download_uri", "sha256"] {
            let mut invalid = base.clone();
            invalid.as_object_mut().unwrap().remove(field);
            assert!(
                serde_json::from_value::<BulkMetadata>(invalid).is_err(),
                "{field}"
            );
        }
        for field in ["id", "updated_at", "jsonl_download_uri"] {
            let mut blank = base.clone();
            blank[field] = json!("  ");
            let metadata: BulkMetadata = serde_json::from_value(blank).unwrap();
            assert!(
                provenance_from_metadata(&metadata, "abc123").is_err(),
                "{field}"
            );
        }
        let mut wrong_type = base.clone();
        wrong_type["type"] = json!("oracle_tags");
        let metadata: BulkMetadata = serde_json::from_value(wrong_type).unwrap();
        assert!(provenance_from_metadata(&metadata, "abc123").is_err());
        let mut wrong_types = base;
        wrong_types["updated_at"] = json!(42);
        assert!(serde_json::from_value::<BulkMetadata>(wrong_types).is_err());
    }

    #[test]
    fn gzip_jsonl_reads_records_and_rejects_malformed_lines() {
        let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
        writeln!(encoder, "{}", json!({"name":"First"})).unwrap();
        writeln!(encoder).unwrap();
        writeln!(encoder, "{}", json!({"name":"Second"})).unwrap();
        let values = read_gzipped_jsonl(encoder.finish().unwrap().as_slice()).unwrap();
        assert_eq!(values.len(), 2);
        assert_eq!(str_field(&values[0], "name"), "First");
        assert_eq!(str_field(&values[1], "name"), "Second");
        assert!(for_each_jsonl("{broken}\n".as_bytes(), |_| true).is_err());
    }

    #[test]
    fn check_reports_missing_or_changed_registry_without_repairing_it() {
        let root = std::env::temp_dir().join(format!("source-registry-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(&root).unwrap();
        let path = root.join("fingerprints.tsv");
        assert!(check_presentation_registry(&path, "canonical\n").is_err());
        fs::write(&path, "stale\n").unwrap();
        assert!(check_presentation_registry(&path, "canonical\n").is_err());
        assert_eq!(fs::read_to_string(&path).unwrap(), "stale\n");
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn token_sources_do_not_shadow_card_fingerprints_and_conflicts_fail_closed() {
        let token = json!({"name":"Shared Name", "layout":"token", "oracle_text":"Token"});
        assert!(source_presentation_card(&token).is_none());
        let mut sources = HashMap::new();
        let mut ambiguous = HashSet::new();
        let card = json!({"name":"Shared Name", "layout":"normal", "oracle_text":"Card"});
        add_presentation_source(&mut sources, &mut ambiguous, "shared_name", &card);
        add_presentation_source(&mut sources, &mut ambiguous, "shared_name", &card);
        assert!(sources.contains_key("shared_name"));
        let other = json!({"name":"Shared Name", "layout":"normal", "oracle_text":"Other"});
        add_presentation_source(&mut sources, &mut ambiguous, "shared_name", &other);
        assert!(ambiguous.contains("shared_name"));
        assert!(!sources.contains_key("shared_name"));
    }
}
